import { execFileSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { describe, expect, it } from 'vitest';
import {
  buildGenerationRecordPair,
  classifyGenerationRecords,
  gitBlobId,
  hashGeneratedDirectory,
  serializeGenerationRecord,
} from '../../../src/shared/generated-bundle-versioning/generationRecords.js';
import { ownedOutput, testGenerationMetadata } from '../support/generationRecordTestUtils.js';

const files = new Map([['index.html', gitBlobId(Buffer.from('<p>index</p>'))], ['B.html', gitBlobId(Buffer.from('<p>B</p>'))]]);
const metadata = testGenerationMetadata([ownedOutput('B.html', 'aaaaaaaaaaaa')]);

function serializedPair(sourceSnapshotId = 'snapshot-test') {
  const generated = testGenerationMetadata(metadata.emitted.owners, sourceSnapshotId);
  const pair = buildGenerationRecordPair(generated.captured, generated.emitted, files);
  return { pair, inputs: serializeGenerationRecord(pair.inputs), output: serializeGenerationRecord(pair.output) };
}

describe('generation records', () => {
  it('matches Git blob IDs for exact generated bytes', () => {
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'meadow-blob-id-'));
    try {
      const filePath = path.join(directory, 'naïve page.html');
      fs.writeFileSync(filePath, Buffer.from([0x3c, 0x70, 0x3e, 0x00, 0xff]));
      const expected = execFileSync('git', ['hash-object', '--no-filters', filePath], { encoding: 'utf8' }).trim();
      expect(gitBlobId(fs.readFileSync(filePath))).toBe(expected);
    } finally {
      fs.rmSync(directory, { recursive: true, force: true });
    }
  });

  it('hashes generated files relative to their version root and ignores Finder metadata', async () => {
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'meadow-hash-generated-'));
    try {
      fs.mkdirSync(path.join(directory, 'nested'));
      fs.writeFileSync(path.join(directory, 'nested', 'page.html'), 'page');
      fs.writeFileSync(path.join(directory, '.DS_Store'), 'finder');
      expect(await hashGeneratedDirectory(directory)).toEqual(new Map([['nested/page.html', gitBlobId(Buffer.from('page'))]]));
    } finally {
      fs.rmSync(directory, { recursive: true, force: true });
    }
  });

  it('classifies a matching pair as valid and exposes its ownership', () => {
    const { inputs, output } = serializedPair();
    const classified = classifyGenerationRecords(inputs, output, files);
    expect(classified.state).toEqual({ kind: 'valid' });
    expect(classified.output?.output.owners).toEqual([ownedOutput('B.html', 'aaaaaaaaaaaa')]);
  });

  it('gives identical output from different source snapshots distinct provenance without changing the output fingerprint', () => {
    const first = serializedPair('snapshot-one').pair;
    const second = serializedPair('snapshot-two').pair;
    expect(first.output.output.fingerprint).toBe(second.output.output.fingerprint);
    expect(first.inputs.generationId).not.toBe(second.inputs.generationId);
    expect(serializedPair('snapshot-one').pair.inputs.generationId).toBe(first.inputs.generationId);
  });

  it('treats results without output identity as legacy, never as corrupt', () => {
    expect(classifyGenerationRecords(null, null, files).state).toEqual({ kind: 'legacy' });
    const legacyInputs = JSON.stringify({ sourceSnapshotId: 'old', bundleConfig: {}, nodeConfig: '', appConfig: {} });
    expect(classifyGenerationRecords(legacyInputs, null, files).state).toEqual({ kind: 'legacy' });
  });

  it('distinguishes a lost or damaged new record from legacy absence', () => {
    const { inputs, output } = serializedPair();
    expect(classifyGenerationRecords(inputs, null, files).state.kind).toBe('corrupt');
    expect(classifyGenerationRecords(null, output, files).state.kind).toBe('corrupt');
    expect(classifyGenerationRecords(inputs, '{not json', files).state.kind).toBe('corrupt');
    const otherGeneration = serializedPair('another-snapshot').output;
    expect(classifyGenerationRecords(inputs, otherGeneration, files).state).toMatchObject({
      kind: 'corrupt',
      diagnostic: expect.stringMatching(/different generations/),
    });
  });

  it('rejects a record that does not describe the actual generated files', () => {
    const { inputs, output } = serializedPair();
    const changed = new Map(files);
    changed.set('index.html', gitBlobId(Buffer.from('<p>edited</p>')));
    expect(classifyGenerationRecords(inputs, output, changed).state).toMatchObject({
      kind: 'corrupt',
      diagnostic: expect.stringMatching(/fingerprint/),
    });
  });

  it('reports metadata from a newer application as unsupported', () => {
    const { inputs, output } = serializedPair();
    const future = JSON.stringify({ ...JSON.parse(output), schemaVersion: 9 });
    expect(classifyGenerationRecords(inputs, future, files).state).toMatchObject({ kind: 'unsupported' });
  });

  it('refuses to build a record that claims an output generation did not emit or one identity at two paths', () => {
    expect(() => buildGenerationRecordPair(metadata.captured, {
      owners: [ownedOutput('missing.html', 'aaaaaaaaaaaa')],
      includedSources: [],
    }, files)).toThrow(/was not emitted/);
    expect(() => buildGenerationRecordPair(metadata.captured, {
      owners: [ownedOutput('index.html', 'aaaaaaaaaaaa'), ownedOutput('B.html', 'aaaaaaaaaaaa')],
      includedSources: [],
    }, files)).toThrow(/more than one page/);
  });
});
